import type { Metadata } from 'next'

import { routing, type Locale } from '@/i18n/routing'

/**
 * Canonical origin for absolute URLs (canonical tags, hreflang, OG, sitemap).
 * Overridable per stage via NEXT_PUBLIC_SITE_URL — on staging this is the
 * CloudFront domain, in production the custom domain. Falls back to the prod
 * domain so a missing env var never yields a broken relative canonical.
 */
export const SITE_URL = (
  process.env.NEXT_PUBLIC_SITE_URL || 'https://bulbau.lu'
).replace(/\/$/, '')

/**
 * Search-engine indexing is OFF by default and only enabled by an explicit
 * `NEXT_PUBLIC_ALLOW_INDEXING=true` (set only on the production stage). This is
 * deliberately an opt-in flag rather than a hostname check: staging is served
 * from a dynamic CloudFront URL with no custom domain, so anything host-based
 * risks accidentally indexing it. Safe default = noindex everywhere until launch
 * flips this on (a Phase 7 step).
 */
export const IS_INDEXABLE = process.env.NEXT_PUBLIC_ALLOW_INDEXING === 'true'

/**
 * The share card used when a page has no photo of its own (public/og-image.png,
 * generated by scripts/generate-brand-assets.mjs). Relative on purpose: Next
 * resolves it against `metadataBase`, so each stage advertises its own origin.
 */
export const DEFAULT_SHARE_IMAGE = {
  url: '/og-image.png',
  width: 1200,
  height: 630,
  alt: 'Bulbau — Energy & Building Services, Luxembourg',
} as const

/**
 * hreflang + canonical for a page. `path` is the locale-independent pathname
 * (e.g. '' for home, '/projects', '/services/12'); this expands it to a
 * canonical for the current locale plus `<link rel="alternate" hreflang>` for
 * every locale and an `x-default` (TECHSPEC §6.11).
 *
 * `x-default` is the UNPREFIXED path (`/`, `/projects`): that URL is the one
 * next-intl's proxy language-negotiates (Accept-Language → 307 to `/en|/fr|/de`),
 * which is exactly what Google defines x-default as — the page for visitors no
 * listed language matches. It also makes the HTML tags agree with the `Link:`
 * header next-intl adds to every response (which already said `x-default` = the
 * unprefixed URL); until 2026-09-18 the two contradicted each other (`/en` in
 * the HTML, `/` in the header), leaving crawlers to pick one.
 */
export function buildAlternates(
  locale: Locale,
  path: string,
): NonNullable<Metadata['alternates']> {
  const clean = path === '/' ? '' : path
  const languages: Record<string, string> = {}
  for (const l of routing.locales) languages[l] = `/${l}${clean}`
  languages['x-default'] = clean || '/'
  return { canonical: `/${locale}${clean}`, languages }
}

/** Shared page-metadata builder: title, description, canonical/hreflang, OG. */
export function pageMetadata(opts: {
  locale: Locale
  path: string
  title?: string
  description?: string
  images?: string[]
}): Metadata {
  const alternates = buildAlternates(opts.locale, opts.path)
  // Only emit a `title` when the page actually has one. Returning
  // `title: undefined` here does NOT inherit the layout's `title.default` — it
  // OVERRIDES it, leaving the page with no <title> (a WCAG 2.4.2 failure caught
  // by the axe gate on the home page, which passes no title). Omitting the key
  // lets the layout default ("%s — Bulbau" template / defaultTitle) apply, while
  // pages that do pass a title still get it (with the template suffix).
  // A page's `openGraph` REPLACES the layout's as a whole (Next merges metadata
  // one top-level key at a time), so the default share image has to be repeated
  // here or every page would lose it. Same for `twitter`.
  const images = opts.images && opts.images.length ? opts.images : [{ ...DEFAULT_SHARE_IMAGE }]
  return {
    ...(opts.title ? { title: opts.title } : {}),
    description: opts.description,
    alternates,
    openGraph: {
      ...(opts.title ? { title: opts.title } : {}),
      description: opts.description,
      url: alternates.canonical as string,
      siteName: 'Bulbau',
      locale: opts.locale,
      type: 'website',
      images,
    },
    twitter: { card: 'summary_large_image', images },
  }
}

/** Matches "<street>, [L-]<4-digit postcode> <locality>", the Luxembourg form. */
const LU_ADDRESS = /^(.+?),\s*(?:L-?)?(\d{4})\s+(.+)$/i

/**
 * Splits a one-line Luxembourg address into schema.org PostalAddress fields.
 * Anything that does not match the usual "street, postcode locality" shape is
 * kept whole as `streetAddress`, so a reformatted address degrades to less
 * structure rather than to a wrong postcode.
 */
export function postalAddress(oneLine: string) {
  const match = LU_ADDRESS.exec(oneLine.trim())
  return match
    ? {
        '@type': 'PostalAddress',
        streetAddress: match[1].trim(),
        postalCode: match[2],
        addressLocality: match[3].trim(),
        addressCountry: 'LU',
      }
    : { '@type': 'PostalAddress', streetAddress: oneLine.trim(), addressCountry: 'LU' }
}

/** Stable identifier for the business node, so other pages can reference it. */
export const BUSINESS_ID = `${SITE_URL}/#business`

/**
 * schema.org data for the business (Home page). Contact details come from
 * Company Info; the registered name, address and VAT number from the Legal
 * Notice, and ONLY once it is published: until then those fields are omitted,
 * never guessed. `HomeAndConstructionBusiness` is the LocalBusiness subtype
 * that matches the services (installations, renovation, solar).
 */
export function businessJsonLd(opts: {
  locale: Locale
  company?: {
    email?: string | null
    phone?: string | null
    facebookUrl?: string | null
    instagramUrl?: string | null
  } | null
  legal?: {
    _status?: string | null
    legalName?: string | null
    legalForm?: string | null
    registeredAddress?: string | null
    vatNumber?: string | null
  } | null
}) {
  const { company, legal } = opts
  const published = legal?._status === 'published'
  const sameAs = [company?.facebookUrl, company?.instagramUrl].filter((u): u is string => Boolean(u))
  return {
    '@context': 'https://schema.org',
    '@type': 'HomeAndConstructionBusiness',
    '@id': BUSINESS_ID,
    name: 'Bulbau',
    url: `${SITE_URL}/${opts.locale}`,
    logo: `${SITE_URL}/icon-512.png`,
    image: `${SITE_URL}${DEFAULT_SHARE_IMAGE.url}`,
    areaServed: { '@type': 'Country', name: 'Luxembourg' },
    ...(company?.email ? { email: company.email } : {}),
    ...(company?.phone ? { telephone: company.phone } : {}),
    ...(sameAs.length ? { sameAs } : {}),
    ...(published && legal?.legalName
      ? { legalName: [legal.legalName, legal.legalForm].filter(Boolean).join(' ') }
      : {}),
    ...(published && legal?.registeredAddress
      ? { address: postalAddress(legal.registeredAddress) }
      : {}),
    ...(published && legal?.vatNumber ? { vatID: legal.vatNumber } : {}),
  }
}
